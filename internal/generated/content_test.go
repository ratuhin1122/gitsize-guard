package generated

import (
	"strings"
	"testing"
)

func TestClassifyContent(t *testing.T) {
	tests := []struct {
		name, content, rule string
	}{
		{"Go header", "// Copyright\n\n// Code generated by mockgen. DO NOT EDIT.\npackage example\n", "Code generated ... DO NOT EDIT"},
		{"generated annotation", "/* @generated */\nexport const x = 1;", "@generated"},
		{"automatic marker", "# This file was automatically generated\n", "This file was automatically generated"},
		{"automatic mixed case", "# THIS FILE WAS AUTOMATICALLY GENERATED\n", "This file was automatically generated"},
		{"by marker", "// auto-generated by tool\n", "auto-generated by"},
		{"by mixed case", "// AuTo-GeNeRaTeD By tool\r\n", "auto-generated by"},
		{"normal source", "package example\nfunc Answer() int { return 42 }\n", ""},
		{"prose far from top", strings.Repeat("// ordinary source\n", 200) + "// generated content is discussed here\n", ""},
		{"marker beyond limit", strings.Repeat(" ", 2048) + "\n// @generated", ""},
		{"binary", "\x00// @generated\n", ""},
		{"binary after marker", "// @generated\n\x00", ""},
		{"empty", "", ""},
		{"short input", "@generated", "@generated"},
		{"short ordinary input", "x", ""},
		{"Go markers on separate lines", "// Code generated by tool\n// DO NOT EDIT\n", ""},
		{"Go incomplete marker", "// Code generated by tool\n", ""},
		{"Go wrong case", "// code generated by tool. do not edit.\n", ""},
		{"annotation wrong case", "// @GENERATED\n", ""},
		{"bare generated word", "// This example explains generated values.\n", ""},
		{"marker ends at limit", strings.Repeat(" ", 2038) + "@generated", "@generated"},
		{"marker crosses limit", strings.Repeat(" ", 2039) + "@generated", ""},
		{"NUL at last inspected byte", "@generated" + strings.Repeat(" ", 2037) + "\x00", ""},
		{"NUL outside inspected prefix", "@generated" + strings.Repeat(" ", 2038) + "\x00", "@generated"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, ok := ClassifyContent([]byte(tt.content))
			want := Match{}
			if tt.rule != "" {
				want = Match{Category: "generated-code", Confidence: Strong, Rule: tt.rule}
			}
			if ok != (tt.rule != "") || got != want {
				t.Fatalf("ClassifyContent() = (%+v, %t), want (%+v, %t)", got, ok, want, tt.rule != "")
			}
		})
	}
}
