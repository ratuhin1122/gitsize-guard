func TestGeneratedReportDeterministic(t *testing.T) {
	files := []FileImpact{{FilePath: "x.log", SizeBytes: 1, GrowthBytes: 1, Generated: &Generated{Category: "logs", Confidence: "weak", Rule: "*.log"}}, {FilePath: "dist/a.js", SizeBytes: 2, GrowthBytes: 2, Generated: &Generated{Category: "build-output", Confidence: "weak", Rule: "dist"}}}
	a := NewReport(append([]FileImpact(nil), files...), DefaultThresholds())
	b := NewReport(append([]FileImpact(nil), files...), DefaultThresholds())
	if !reflect.DeepEqual(a, b) {
		t.Fatalf("nondeterministic reports: %+v %+v", a, b)
	}
}

// Intentional tracked files must be silent even when their path or new header
// would otherwise match. These are the Taintwatch log/launcher regressions.
func TestGeneratedTrackedFilesAreSilent(t *testing.T) {
	for _, name := range []string{"race.log", filepath.Join("bin", "README.md"), filepath.Join("bin", "taintwatch-launcher"), "output.go", filepath.Join("node_modules", "intentional.js")} {
		t.Run(filepath.ToSlash(name), func(t *testing.T) {
			repo := newRepo(t)
			writeFile(t, filepath.Join(repo, name), []byte("intentional original"))
			git(t, repo, "add", "--", name)
			git(t, repo, "commit", "-qm", "intentional tracked file")
			content := []byte("// Code generated by x. DO NOT EDIT.\nchanged intentional file\n")
			writeFile(t, filepath.Join(repo, name), content)
			git(t, repo, "add", "--", name)
			defer assertGitFilesUnchanged(t, repo)()
			cfg := DefaultGeneratedConfig()
			cfg.TimeBudget = time.Minute
			for _, kind := range []Kind{KindStaged, KindFiles} {
				sels := []Selection{{Dir: repo, Kind: kind, Pathspecs: []string{name}}}
				report, err := AnalyzeWithConfig(sels, Thresholds{1000, 2000}, NearDupConfig{}, cfg)
				if err != nil {
					t.Fatal(err)
				}
				baseline, err := AnalyzeWithConfig(sels, Thresholds{1000, 2000}, NearDupConfig{}, GeneratedConfig{})
				if err != nil {
					t.Fatal(err)
				}
				if report.GeneratedFiles != 0 || len(report.Notes) != 0 || len(report.Reasons) != 0 || report.RiskLevel != RiskLow || len(report.Files) != 1 || report.Files[0].Generated != nil || report.GrowthBytes != baseline.GrowthBytes {
					t.Fatalf("tracked file flagged (kind=%v): %+v, baseline=%+v", kind, report, baseline)
				}
			}
			file := FileImpact{FilePath: filepath.ToSlash(name), SizeBytes: int64(len(content)), GrowthBytes: int64(len(content))}
			notes := CheckGenerated(repo, &file, content, cfg)
			if file.Generated != nil || len(notes) != 0 || file.GrowthBytes != int64(len(content)) {
				t.Fatalf("Write tracked file flagged: %+v, notes=%v", file, notes)
			}
		})
	}
}

func TestGeneratedTrackedRenamesAreSilent(t *testing.T) {
	for _, edited := range []bool{false, true} {
		t.Run(fmt.Sprint("edited=", edited), func(t *testing.T) {
			repo := newRepo(t)
			content := strings.Repeat("intentional source line\n", 100)
			writeFile(t, filepath.Join(repo, "original.txt"), []byte(content))
			git(t, repo, "add", "original.txt")
			git(t, repo, "commit", "-qm", "original")
			git(t, repo, "mv", "original.txt", "renamed.log")
			if edited {
				writeFile(t, filepath.Join(repo, "renamed.log"), []byte(content+"// @generated\n"))
				git(t, repo, "add", "renamed.log")
			}
			defer assertGitFilesUnchanged(t, repo)()
			cfg := DefaultGeneratedConfig()
			cfg.TimeBudget = time.Minute
			sels := []Selection{{Dir: repo, Kind: KindStaged}}
			report, err := AnalyzeWithConfig(sels, Thresholds{10000, 20000}, NearDupConfig{}, cfg)
			if err != nil {
				t.Fatal(err)
			}
			baseline, err := AnalyzeWithConfig(sels, Thresholds{10000, 20000}, NearDupConfig{}, GeneratedConfig{})
			if err != nil {
				t.Fatal(err)
			}
			if report.GeneratedFiles != 0 || len(report.Notes) != 0 || len(report.Reasons) != 0 || report.RiskLevel != RiskLow || len(report.Files) != 1 || report.Files[0].Generated != nil || report.GrowthBytes != baseline.GrowthBytes {
				t.Fatalf("rename flagged: %+v baseline=%+v", report, baseline)
			}
			file := FileImpact{FilePath: "renamed.log"}
			if notes := CheckGenerated(repo, &file, []byte(content), cfg); len(notes) != 0 || file.Generated != nil {
				t.Fatalf("rename Write flagged: %+v notes=%v", file, notes)
			}
		})
	}
}
