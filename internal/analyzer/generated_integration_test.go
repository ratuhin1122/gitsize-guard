func TestGeneratedAnalysisPolicy(t *testing.T) {
	for _, tc := range []struct {
		name, file, content, risk, confidence string
		thresholds                            Thresholds
		tracked, ignored, disabled, staged    bool
	}{
		{name: "strong low to medium", file: filepath.Join("node_modules", "pkg", "a.js"), content: "12345678", risk: RiskMedium, confidence: "strong", thresholds: Thresholds{100, 200}},
		{name: "strong medium stays medium", file: filepath.Join("node_modules", "a.js"), content: "12345678", risk: RiskMedium, confidence: "strong", thresholds: Thresholds{5, 20}},
		{name: "strong high stays high", file: filepath.Join("node_modules", "a.js"), content: "12345678", risk: RiskHigh, confidence: "strong", thresholds: Thresholds{5, 8}},
		{name: "weak log", file: "server.log", content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "weak map", file: "app.js.map", content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "weak minified", file: "app.min.js", content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "weak binary", file: "tool.exe", content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "weak coverage", file: "coverage/report.txt", content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "weak note only", file: filepath.Join("dist", "a.js"), content: "12345678", risk: RiskLow, confidence: "weak", thresholds: Thresholds{100, 200}},
		{name: "tracked folder suppressed", file: filepath.Join("dist", "a.js"), content: "12345678", risk: RiskLow, tracked: true, thresholds: Thresholds{100, 200}},
		{name: "tracked strong folder suppressed", file: filepath.Join("node_modules", "a.js"), content: "12345678", risk: RiskLow, tracked: true, thresholds: Thresholds{100, 200}},
		{name: "ignored weak becomes strong", file: filepath.Join("dist", "a.js"), content: "12345678", risk: RiskMedium, confidence: "strong", ignored: true, staged: true, thresholds: Thresholds{100, 200}},
		{name: "ignored ordinary path becomes strong", file: "data.txt", content: "12345678", risk: RiskMedium, confidence: "strong", ignored: true, staged: true, thresholds: Thresholds{100, 200}},
		{name: "content marker", file: "output.go", content: "// Code generated by tool. DO NOT EDIT.\npackage output\n", risk: RiskMedium, confidence: "strong", thresholds: Thresholds{100, 200}},
		{name: "staged content marker", file: "output.go", content: "// @generated\npackage output\n", risk: RiskMedium, confidence: "strong", staged: true, thresholds: Thresholds{100, 200}},
		{name: "content upgrades weak path", file: filepath.Join("dist", "a.go"), content: "// @generated\npackage output\n", risk: RiskMedium, confidence: "strong", thresholds: Thresholds{100, 200}},
		{name: "content beyond prefix ignored", file: "output.go", content: strings.Repeat(" ", 2048) + "// @generated", risk: RiskLow, thresholds: Thresholds{10000, 20000}},
		{name: "disabled", file: filepath.Join("node_modules", "a.js"), content: "// @generated", risk: RiskLow, disabled: true, thresholds: Thresholds{100, 200}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			repo := newRepo(t)
			if tc.tracked {
				old := filepath.Join(filepath.Dir(tc.file), "existing.txt")
				writeFile(t, filepath.Join(repo, old), []byte("existing"))
				git(t, repo, "add", "--", old)
				git(t, repo, "commit", "-qm", "intentional folder")
			}
			writeFile(t, filepath.Join(repo, tc.file), []byte(tc.content))
			if tc.ignored {
				writeFile(t, filepath.Join(repo, ".gitignore"), []byte(filepath.ToSlash(tc.file)+"\n"))
			}
			kind := KindFiles
			if tc.staged {
				git(t, repo, "add", "-f", "--", tc.file)
				kind = KindStaged
				// Staged analysis must read the index, not newer worktree content.
				writeFile(t, filepath.Join(repo, tc.file), []byte("ordinary replacement"))
			}
			defer assertGitFilesUnchanged(t, repo)()
			cfg := DefaultGeneratedConfig()
			cfg.Enabled = !tc.disabled
			cfg.TimeBudget = time.Minute
			sels := []Selection{{Dir: repo, Kind: kind, Pathspecs: []string{tc.file}}}
			report, err := AnalyzeWithConfig(sels, tc.thresholds, NearDupConfig{}, cfg)
			if err != nil {
				t.Fatal(err)
			}
			baseline, err := AnalyzeWithConfig(sels, tc.thresholds, NearDupConfig{}, GeneratedConfig{})
			if err != nil {
				t.Fatal(err)
			}
			if report.RiskLevel != tc.risk || report.GrowthBytes != baseline.GrowthBytes || report.GrowthBytes != int64(len(tc.content)) {
				t.Fatalf("report=%+v baseline=%+v", report, baseline)
			}
			if len(report.Files) != 1 {
				t.Fatalf("files=%+v", report.Files)
			}
			g := report.Files[0].Generated
			if tc.confidence == "" {
				if g != nil || report.GeneratedFiles != 0 || len(report.Notes) != 0 {
					t.Fatalf("unexpected generated result: %+v", report)
				}
			} else {
				if g == nil || g.Confidence != tc.confidence || g.IgnoredByGitignore != tc.ignored || report.GeneratedFiles != 1 || report.GeneratedByCategory[g.Category] != 1 {
					t.Fatalf("generated=%+v report=%+v", g, report)
				}
				if tc.confidence == "weak" {
					if len(report.Notes) != 1 || len(report.Reasons) != 0 {
						t.Fatalf("weak result=%+v", report)
					}
				} else if !strings.Contains(strings.Join(report.Reasons, "\n"), "looks like generated") || !strings.Contains(report.Recommendation, "git rm -r --cached <folder>") {
					t.Fatalf("missing advice=%+v", report)
				}
			}
			text, err := report.ToJSON()
			if err != nil {
				t.Fatal(err)
			}
			var decoded map[string]any
			if err = json.Unmarshal([]byte(text), &decoded); err != nil {
				t.Fatal(err)
			}
			_, present := decoded["generated_files"]
			if present != (tc.confidence != "") {
				t.Fatalf("JSON=%s", text)
			}
		})
	}
}

func TestGeneratedAggregation(t *testing.T) {
	files := make([]FileImpact, 5000)
	for i := range files {
		files[i] = FileImpact{FilePath: filepath.ToSlash(filepath.Join("node_modules", fmt.Sprint(i), "a.js")), SizeBytes: 10, GrowthBytes: 10, Generated: &Generated{Category: "dependencies", Confidence: "strong", Rule: "node_modules"}}
	}
	report := NewReport(files, Thresholds{100000, 200000})
	if report.GeneratedFiles != 5000 || report.GeneratedByCategory["dependencies"] != 5000 || report.GrowthBytes != 50000 || report.RiskLevel != RiskMedium || len(report.Reasons) != 1 || len(report.Files) != maxReportedFiles {
		t.Fatalf("report=%+v", report)
	}
	if !strings.Contains(report.Reasons[0], "node_modules/") || !strings.Contains(report.Reasons[0], "5000 files, "+HumanReadableSize(50000)+" total") {
		t.Fatalf("reason=%s", report.Reasons[0])
	}
}

func TestGeneratedPipelineAggregationAndCap(t *testing.T) {
	repo := newRepo(t)
	for i := 0; i < 142; i++ {
		writeFile(t, filepath.Join(repo, "node_modules", fmt.Sprintf("%03d.js", i)), []byte("dependency"))
	}
	defer assertGitFilesUnchanged(t, repo)()
	sels := []Selection{{Dir: repo, Kind: KindPending}}
	cfg := DefaultGeneratedConfig()
	cfg.TimeBudget = time.Minute
	report, err := AnalyzeWithConfig(sels, DefaultThresholds(), NearDupConfig{}, cfg)
	if err != nil || report.GeneratedFiles != 142 || report.GeneratedByCategory["dependencies"] != 142 || len(report.Reasons) != 1 || report.GrowthBytes != 1420 {
		t.Fatalf("report=%+v err=%v", report, err)
	}
	if !strings.Contains(report.Reasons[0], "142 files") {
		t.Fatalf("reason=%s", report.Reasons[0])
	}
	cfg.MaxPaths = 10
	capped, err := AnalyzeWithConfig(sels, DefaultThresholds(), NearDupConfig{}, cfg)
	if err != nil || capped.GeneratedFiles != 10 || capped.GrowthBytes != report.GrowthBytes || !strings.Contains(strings.Join(capped.Notes, "\n"), "limited to 10 paths") {
		t.Fatalf("capped=%+v err=%v", capped, err)
	}
}

